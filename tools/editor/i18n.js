/* OpenMTV editor -- the interface language: the editor's own words in English or German.
 * (The game texts being edited and previewed -- titles, genres, countries, the cards -- follow
 * the "Game texts" toggle instead; they come from the game per language.)
 *   T(en, params)              the text in the interface language.  The English text is the
 *                              key; {name} takes params.name (the key "Film #{id}" with
 *                              { id: 31 }).  A key may carry a context after '|' ("in|pool":
 *                              another German word than "in"); English drops it.
 *                              The keys are literals: the self-test reads them from the sources
 *                              (T, TP, playLog and mpLog calls and index.html) and checks DE against them.
 *   TP(n, one, many, params)   the plural variant for n ({n} is n)
 *   numFmt(v)                  a number as the interface language writes it (1,000 / 1.000)
 *   onUiLang(fn)               fn now and after every switch (texts held in data: the sections)
 *   setUiLang(lang, o)         switch, keep the choice (o.keep !== false), draw everything again
 * The choice: ?ui=de / ?ui=en, else (not in the self-test) the one kept in this browser, else
 * the browser's language, else English.  DE: English -> German; a key without a German text
 * is recorded (UI.missing, checked by the self-test). */
'use strict';

const UI_LANGS = ['en', 'de'];
const UI = { lang: 'en', missing: new Set(), hooks: [] };
const UI_KEY = 'madtv-editor-ui';

function T(en, params) {
  let s = en;
  if (UI.lang === 'de') {
    const d = DE[en];
    if (d === undefined) UI.missing.add(en); else s = d;
  }
  const bar = s.indexOf('|');
  if (bar >= 0) s = s.slice(0, bar);
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}
const TP = (n, one, many, params) => T(n === 1 ? one : many, Object.assign({ n }, params));
const numFmt = (v) => Number(v).toLocaleString(UI.lang === 'de' ? 'de-DE' : 'en-US');
function onUiLang(fn) { UI.hooks.push(fn); fn(); }

/* the first choice: ?ui=, else (not in the self-test) the one kept, else the browser's language */
function pickUiLang(search, kept, browser) {
  const q = new URLSearchParams(search);
  if (UI_LANGS.includes(q.get('ui'))) return q.get('ui');
  if (q.has('selftest')) return 'en';
  if (UI_LANGS.includes(kept)) return kept;
  return /^de\b/i.test(browser || '') ? 'de' : 'en';
}
function keptUiLang() { try { return localStorage.getItem(UI_KEY); } catch (e) { return null; } }     /* private window */
UI.lang = pickUiLang(location.search, keptUiLang(), navigator.language);

/* the page's own texts (index.html): [data-i18n] elements -- their text (when they hold no
   other element) and their data-tip, placeholder, aria-label; the English stays in STATIC_EN */
const STATIC_EN = new WeakMap();
const STATIC_ATTRS = ['data-tip', 'placeholder', 'aria-label'];
function translateStatic() {
  document.documentElement.lang = UI.lang;
  if (!/^SELFTEST/.test(document.title)) document.title = T('OpenMTV Editor');
  for (const el of document.querySelectorAll('[data-i18n]')) {
    let en = STATIC_EN.get(el);
    if (!en) {
      en = { text: el.children.length || el.dataset.i18n === 'attrs' ? null : el.textContent.trim() };
      for (const a of STATIC_ATTRS) if (el.hasAttribute(a)) en[a] = el.getAttribute(a);
      STATIC_EN.set(el, en);
    }
    if (en.text) el.textContent = T(en.text);
    for (const a of STATIC_ATTRS) if (en[a]) el.setAttribute(a, T(en[a]));
  }
  for (const b of document.querySelectorAll('.uilang')) { const on = b.dataset.ui === UI.lang; b.classList.toggle('on', on); b.setAttribute('aria-pressed', on ? 'true' : 'false'); }
}
/* switch: the data's texts again (hooks), the page's, then everything drawn again -- the
   records, unsaved changes and undo stay as they are */
function setUiLang(lang, o = {}) {
  if (!UI_LANGS.includes(lang)) return;
  UI.lang = lang;
  if (o.keep !== false) { try { localStorage.setItem(UI_KEY, lang); } catch (e) { /* ignore */ } }
  for (const fn of UI.hooks) fn();
  translateStatic();
  if (typeof uiLangChanged === 'function') uiLangChanged();
}

