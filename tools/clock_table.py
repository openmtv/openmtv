#!/usr/bin/env python3
"""Entries counted by the logical clock (runtime.h: --logical-time):
image-relative linear addresses of the decompiled functions in src/, read
from the "/* SEG:OFF  ..." comment above each function.  Left out: a function
whose body uses FUNC_TICK_NOCLOCK (its call count depends on original stack
garbage, so the engines would count it differently) or RTL_ENTRY / RTL_ENTRY_NOPOLL
(a run-time library function rewritten in C, src/rtl*.c: not part of the
clock).  The RTL_ENTRY functions go into a second table, rtl_exact_keys (SEG<<16 |
OFF): the difftest checks that they keep the original's exact time.

    clock_table.py OUT.c src/*.c
"""
import re, sys


def entries(paths):
    out, skipped, rtl = set(), set(), set()
    for p in paths:
        text = open(p).read()
        heads = list(re.finditer(r'^/\* ([0-9A-F]{4}):([0-9A-F]{4})  ', text, re.M))
        for i, m in enumerate(heads):
            body = text[m.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
            lin = (int(m.group(1), 16) << 4) + int(m.group(2), 16)
            rtl_fn = re.search(r'RTL_ENTRY(_NOPOLL)?\(', body)
            (skipped if 'FUNC_TICK_NOCLOCK(' in body or rtl_fn else out).add(lin)
            if rtl_fn:
                rtl.add((int(m.group(1), 16) << 16) | int(m.group(2), 16))
    return sorted(out), sorted(skipped), sorted(rtl)


def main():
    ents, skipped, rtl = entries(sys.argv[2:])
    lines = ['/* Generated by tools/clock_table.py from src/ -- do not edit. */',
             '#include "runtime.h"',
             '/* not counted: %s */' % (', '.join('%05X' % x for x in skipped) or 'none'),
             'const u32 clock_entry_table[] = {']
    for n in range(0, len(ents), 10):
        lines.append('    ' + ', '.join('0x%05X' % x for x in ents[n:n + 10]) + ',')
    lines += ['};', 'const int clock_entry_count = %d;' % len(ents),
              '/* run-time library functions rewritten in C: exact time (difftest) */',
              'const u32 rtl_exact_keys[] = {']
    for n in range(0, len(rtl), 8):
        lines.append('    ' + ', '.join('0x%08X' % x for x in rtl[n:n + 8]) + ',')
    lines += ['    0', '};', 'const int rtl_exact_count = %d;' % len(rtl)]
    open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
