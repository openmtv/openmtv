#!/usr/bin/env python3
"""build/hr_data.c for --filter hr (src/hr_data.h): the rules of
runtime/hr_rules.txt, the 4x font of tools/hrfont/font*.txt, the trial
fonts of tools/hrfont/try/NAME/ (hrfont.py ttf; the game: HR_FONT=NAME) and
the animation parts of runtime/ki_parts.txt (AI pictures, src/ki_make.c).

  hrdata.py OUT.c
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import hrfont

RULES = {'nearest': 'HR_NEAREST', 'mmpx': 'HR_MMPX', 'mmpx-wrap': 'HR_WRAP', 'font': 'HR_FONT', 'thin': 'HR_THIN'}


def rules():
    out = []
    for n, line in enumerate(open(os.path.join(ROOT, 'runtime', 'hr_rules.txt')), 1):
        line = line.split('#')[0].split()
        if not line:
            continue
        res, default, extra = int(line[0]), line[1], line[2:]
        if default not in RULES:
            sys.exit('runtime/hr_rules.txt:%d: rule %r' % (n, default))
        for e in extra:
            rng, rule = e.split('=')
            a, _, b = rng.partition('-')
            if rule not in RULES:
                sys.exit('runtime/hr_rules.txt:%d: rule %r' % (n, rule))
            out.append((res, int(a), int(b or a), RULES[rule]))
        out.append((res, 0, 255, RULES[default]))
    return out


def ki_parts():
    """runtime/ki_parts.txt (tools/hrai.py parts) as ([(res, k, kind, a, b, x, y)],
    [(r2, k2, res, k, x, y)]), sorted: kind 0 none, 1 room a, 2 sprite b of bank a,
    3 in the group of sprite b of bank a; the covers by the picture they lie on"""
    out, covers = [], []
    for n, line in enumerate(open(os.path.join(ROOT, 'runtime', 'ki_parts.txt')), 1):
        w = line.split('#')[0].split()
        if not w:
            continue
        if len(w) == 3 and w[2] == 'none':
            out.append((int(w[0]), int(w[1]), 0, 0, 0, 0, 0))
        elif len(w) == 6 and w[2] == 'room':
            out.append((int(w[0]), int(w[1]), 1, int(w[3]), 0, int(w[4]), int(w[5])))
        elif len(w) == 7 and w[2] == 'sprite':
            out.append((int(w[0]), int(w[1]), 2, int(w[3]), int(w[4]), int(w[5]), int(w[6])))
        elif len(w) == 7 and w[2] == 'group':
            out.append((int(w[0]), int(w[1]), 3, int(w[3]), int(w[4]), int(w[5]), int(w[6])))
        elif len(w) == 7 and w[2] == 'cover':
            covers.append((int(w[3]), int(w[4]), int(w[0]), int(w[1]), int(w[5]), int(w[6])))
        else:
            sys.exit('runtime/ki_parts.txt:%d: %r' % (n, line))
    groups = {}
    for p in out:
        if p[2] == 3:
            groups.setdefault(p[3:5], []).append(p[:2])
    for g, m in groups.items():         # (src/ki_make.c: a group from its first sprite, at most KI_GROUP of them)
        if g not in m or len(m) > 16:
            sys.exit('runtime/ki_parts.txt: group %d %d: %s' % (g + ('not its first sprite' if g not in m else 'more than 16 sprites',)))
    return sorted(out), sorted(covers)


def main(path):
    lines = ['/* generated by tools/hrdata.py from runtime/hr_rules.txt and tools/hrfont/ -- do not edit */',
             '#include "hr_data.h"', '']
    r = rules()
    lines.append('const HrRule hr_rules[] = {\n    %s\n};' % ',\n    '.join('{%d, %d, %d, %s}' % x for x in r))
    lines.append('const int hr_rule_count = %d;' % len(r))
    sets = [None] + sorted(d for d in os.listdir(hrfont.TRY) if os.path.isdir(os.path.join(hrfont.TRY, d))) \
        if os.path.isdir(hrfont.TRY) else [None]
    for i, s in enumerate(sets):
        entries = []
        for res in hrfont.FONTS:
            for k, (w, h, px) in sorted(hrfont.load(res, s).items()):
                name = 'g%d_%d_%d' % (i, res, k)
                lines.append('static const unsigned char %s[%d] = {%s};' % (name, len(px), ','.join(map(str, px))))
                entries.append('{%d, %d, %d, %s}' % (res, k, h, name))
        lines.append('static const HrGlyph set%d[] = {\n    %s\n};' % (i, ',\n    '.join(entries)))
    lines.append('const HrFontSet hr_font_sets[] = {\n    %s\n};' % ',\n    '.join(
        '{"%s", set%d, %d}' % (s or '', i, sum(len(hrfont.load(r, s)) for r in hrfont.FONTS)) for i, s in enumerate(sets)))
    lines.append('const int hr_font_set_count = %d;' % len(sets))
    parts, covers = ki_parts()
    lines.append('const KiPart ki_parts[] = {\n    %s\n};' % ',\n    '.join('{%d, %d, %d, %d, %d, %d, %d}' % p for p in parts or [(0,) * 7]))
    lines.append('const int ki_part_count = %d;' % len(parts))
    lines.append('const KiCover ki_covers[] = {\n    %s\n};' % ',\n    '.join('{%d, %d, %d, %d, %d, %d}' % c for c in covers or [(0,) * 6]))
    lines.append('const int ki_cover_count = %d;' % len(covers))
    tmp = path + '.tmp'
    open(tmp, 'w').write('\n'.join(lines) + '\n')
    os.replace(tmp, path)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
