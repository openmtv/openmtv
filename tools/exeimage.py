#!/usr/bin/env python3
"""The part of MTV.EXE the decompiled build still needs, as C: so that
build/mtv-dec runs without the EXE (players bring only SOURCE1.RSC and
SOURCE2.RSC).

    python3 tools/exeimage.py build/MTV_U.EXE build/exe_image.c

What the decompiled build reads from the loaded EXE is data: the initial
image of the data segment (DGROUP 39D4:0000 up to the end of the load
module, which runs 0x151 bytes into the stack segment 4447) with the
relocations that fall into it, and the header's start values.  Its code is
C (src/); only 202 bytes of segment 371E are still read or executed --
the sound driver's signatures, jump stubs and fallback -- and
src/rtl_snd.c writes those itself (snd_code_init).  Measured by zeroing
the code part of the EXE: every scenario plays the same game
(docs/STATE.md; tools/exefree.py checks it).

The generated file is a build product (build/), like gen/: it is made
from the user's own MTV.EXE and is not committed."""
import hashlib
import struct
import sys

DGROUP = 0x39D4


def image(path):
    d = open(path, 'rb').read()
    if d[:2] != b'MZ':
        sys.exit('%s: not an MZ exe' % path)
    last, pages, nrel, hdr = struct.unpack_from('<4H', d, 2)
    ss, sp, _, ip, cs, relo = struct.unpack_from('<6H', d, 0x0E)
    hdr *= 16
    size = (pages - 1) * 512 + (last or 512) - hdr
    img = d[hdr:hdr + size]
    lo = DGROUP * 16
    rel = []
    for i in range(nrel):
        o, s = struct.unpack_from('<HH', d, relo + 4 * i)
        a = s * 16 + o
        if a + 1 >= lo:
            if a < lo:
                sys.exit('relocation at %05X straddles the start of the data segment' % a)
            rel.append(a - lo)
    return {'sha256': hashlib.sha256(d).hexdigest(), 'size': size, 'data_off': lo,
            'data': img[lo:], 'rel': sorted(rel), 'nrel': nrel,
            'ss': ss, 'sp': sp, 'cs': cs, 'ip': ip}


def c_source(im, src_name):
    out = ['/* Generated by tools/exeimage.py from %s (sha256 %s): do not edit.' % (src_name, im['sha256']),
           ' * The initial data segment of MTV.EXE and its start values: what the',
           ' * decompiled build loads instead of the EXE (runtime/main.c). */',
           '#include "runtime.h"',
           '',
           'void snd_code_init(void);          /* src/rtl_snd.c: the 202 bytes of 371E */',
           '',
           'static const u8 data[%d] = {' % len(im['data'])]
    b = im['data']
    for i in range(0, len(b), 16):
        out.append('    ' + ''.join('0x%02X,' % x for x in b[i:i + 16]))
    out.append('};')
    out.append('static const u32 rel[%d] = { %s };' % (max(1, len(im['rel'])),
                                                     ', '.join('0x%04X' % r for r in im['rel']) or '0'))
    out.append('')
    out.append('static const struct builtin_image img = {')
    out.append('    .image_bytes = %d, .data_off = 0x%05X, .data_len = %d, .data = data,' %
               (im['size'], im['data_off'], len(b)))
    out.append('    .nrel = %d, .rel = rel, .nrel_exe = %d,' % (len(im['rel']), im['nrel']))
    out.append('    .ss = 0x%04X, .sp = 0x%04X, .cs = 0x%04X, .ip = 0x%04X,' %
               (im['ss'], im['sp'], im['cs'], im['ip']))
    out.append('    .code_init = snd_code_init, .sha256 = "%s",' % im['sha256'])
    out.append('};')
    out.append('const struct builtin_image *builtin_image = &img;')
    return '\n'.join(out) + '\n'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    im = image(sys.argv[1])
    open(sys.argv[2], 'w').write(c_source(im, sys.argv[1].rsplit('/', 1)[-1]))
    print('%s: data segment %d bytes, %d of %d relocations, from %s' %
          (sys.argv[2], len(im['data']), len(im['rel']), im['nrel'], sys.argv[1]))


if __name__ == '__main__':
    main()
